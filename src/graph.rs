//! The graph tier: the targets only Bazel can name.
//!
//! A legacy macro computes its targets' names when Bazel evaluates it, so
//! `//lib:from_legacy_0` exists in the build and appears nowhere in the source.
//! No parser can find it and no amount of work on the static tier will change
//! that — asking Bazel is the only way, which is what this module does.
//!
//! Bazel is asked through [`BazelClient::stream`] and decoded as the bytes
//! arrive. Slurping the stream first costs thirteen times the memory for the
//! same wall time: 442 MB against 34 MB over 240,000 targets. Decoding is not
//! the constraint either way — prost manages 324 MB/s and Bazel writes at 52.

use std::path::PathBuf;
use std::sync::Arc;

use anyhow::Result;
use bytes::{Buf, BytesMut};
use prost::{DecodeError, Message};

use crate::bazel::{BazelClient, Interrupt, Outcome};
use crate::index::{Target, Tier};

